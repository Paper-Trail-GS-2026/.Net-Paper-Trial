CREATE TABLE PT_USER (
    ID BIGINT IDENTITY(1000, 1) NOT NULL CONSTRAINT PK_PT_USER PRIMARY KEY,
    NAME NVARCHAR(120) NOT NULL,
    EMAIL NVARCHAR(254) NOT NULL CONSTRAINT UQ_PT_USER_EMAIL UNIQUE,
    PASSWORD_HASH NVARCHAR(255) NOT NULL,
    ROLE_NAME NVARCHAR(10) NOT NULL CONSTRAINT DF_PT_USER_ROLE DEFAULT 'CITIZEN',
    CREATED_AT DATETIMEOFFSET(7) NOT NULL CONSTRAINT DF_PT_USER_CREATED DEFAULT TODATETIMEOFFSET(SYSUTCDATETIME(), '+00:00'),
    CONSTRAINT CK_PT_USER_ID CHECK (ID BETWEEN 1 AND 999999999999999999),
    CONSTRAINT CK_PT_USER_NAME CHECK (LEN(TRIM(NAME)) > 0),
    CONSTRAINT CK_PT_USER_EMAIL CHECK (LEN(TRIM(EMAIL)) > 0 AND EMAIL COLLATE Latin1_General_100_BIN2 = LOWER(TRIM(EMAIL)) COLLATE Latin1_General_100_BIN2),
    CONSTRAINT CK_PT_USER_ROLE CHECK (ROLE_NAME IN ('CITIZEN', 'MANAGER'))
