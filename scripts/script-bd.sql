CREATE TRIGGER TRG_PT_ITEM_AUDIT
ON PT_PREPARATION_ITEM
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;
    INSERT INTO PT_ITEM_AUDIT (
        ITEM_ID, OPERATION, DATABASE_USER,
        OLD_PREPARATION_ID, NEW_PREPARATION_ID, OLD_REQUIREMENT_ID, NEW_REQUIREMENT_ID,
        OLD_TITLE, NEW_TITLE, OLD_REQUIRED, NEW_REQUIRED, OLD_COMPLETED, NEW_COMPLETED
    )
    SELECT
        COALESCE(i.ID, d.ID),
        CASE WHEN d.ID IS NULL THEN 'INSERT' WHEN i.ID IS NULL THEN 'DELETE' ELSE 'UPDATE' END,
        ORIGINAL_LOGIN(),
        d.PREPARATION_ID, i.PREPARATION_ID, d.REQUIREMENT_ID, i.REQUIREMENT_ID,
        d.TITLE, i.TITLE, d.REQUIRED, i.REQUIRED, d.COMPLETED, i.COMPLETED
    FROM inserted i
    FULL OUTER JOIN deleted d ON i.ID = d.ID;
END;
GO
